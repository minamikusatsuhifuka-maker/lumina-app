// 265d: ④発信戦略の数値の扱い（§8-1）。
// KBの数値（インプレッション倍率6倍/15倍・購入率・40倍シグナル等）は二次情報の集約値であり、
// 断定的な効果予測として提示してはならない。プロンプトで併記を指示するだけでなく、
// **サーバー側で必ず定型の注意書きを末尾に付与**する（AIの遵守に依存しない決定的な担保）。

export const STRATEGY_NUMBERS_DISCLAIMER = `---

## ⚠️ 本戦略の数値の扱いについて（必読）

- 本戦略に含まれる数値（インプレッション倍率・購入率・「40倍」等のシグナル重み・時間帯・価格帯）は、
  **実践知見の集約値であり、公式の確定値ではありません**。自アカウントの実測で必ず補正してください。
- 特にXプレミアムのインプレッション倍率（プレミアム約6倍／プラス約15倍）は**中央値の比較であり対照実験ではありません**。
  課金者はそもそも投稿頻度・熱量が高い可能性があり（自己選択バイアス）、倍率がすべて課金の効果とは限りません。
- 本戦略はAIによる提案です。実際の成果（フォロワー増・収益）を保証するものではありません。`;

/** 生成済み戦略の末尾に注意書きを1回だけ付ける（既にあれば二重付与しない） */
export function appendStrategyDisclaimer(content: string): string {
  const c = (content || '').trim();
  if (!c) return c;
  if (c.includes('本戦略の数値の扱いについて')) return c;
  return `${c}\n\n${STRATEGY_NUMBERS_DISCLAIMER}`;
}
