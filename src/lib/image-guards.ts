// - imagePromptRules: 起案時にAIへ渡す【必ず反映】＋【禁止】（対象名詞だけ差し替え可能）
// - IMAGE_GUARD_SUFFIX: 生成時にユーザー編集後プロンプトへ必ず連結する厳守ガード
//   （編集で消されても効かせる＝サーバ側で常時付与。緩和・省略しない＝226承認条件）
// 文言は226実装時のものを変更しない（kindle側の挙動を変えないため）。
