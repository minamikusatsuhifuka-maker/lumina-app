// 不正・未知のキーは既定目的に落とす
export function getKindlePurpose(key: unknown): KindlePurpose {
  if (typeof key === 'string' && key in KINDLE_PURPOSES) {
    return KINDLE_PURPOSES[key as KindlePurposeKey];
  }
  return KINDLE_PURPOSES[DEFAULT_KINDLE_PURPOSE];
}

